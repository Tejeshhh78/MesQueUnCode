"""Run a fixed old-versus-new comparison without training or parameter tuning."""

import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

from games import GAME, GAMES, require
from possession.__main__ import sha256


ROOT = Path(__file__).resolve().parent
BASELINE = "baseline_smooth50"
SOLUTION = "MesQueUnCode"


def score_predictions(output, bootstrap, environment):
    """Score the two fixed CSVs and reject changes while evaluation is running."""
    predictions = {name: output / "results" / f"{name}.csv" for name in (BASELINE, SOLUTION)}
    hashes = {name: sha256(path) for name, path in predictions.items()}
    subprocess.run([sys.executable, str(ROOT / "evaluation" / "run_evaluation.py"),
                    "--gt", "public", "--results", str(output / "results"),
                    "--out", str(output / "evaluation"), "--bootstrap", str(bootstrap), "--no-detail"],
                   cwd=ROOT, env=environment, check=True)
    if hashes != {name: sha256(path) for name, path in predictions.items()}:
        raise RuntimeError("Predictions changed during evaluation; rerun the comparison")
    metrics = {name: json.loads((output / "evaluation" / "reports" / f"{name}.json")
                               .read_text(encoding="utf-8")) for name in predictions}
    return metrics, hashes


def write_quality_summary(output, metrics, hashes, *, reused_predictions=False):
    """Explain possession detection using the official aggregate matching results."""
    baseline, solution = metrics[BASELINE], metrics[SOLUTION]
    for key in ("ground_truth", "n_graded", "n_gt_spells", "spell_iou_headline", "bootstrap_n"):
        if baseline[key] != solution[key]:
            raise ValueError(f"Incompatible evaluation scope: {key}")
    thresholds = sorted(baseline["spell_f1"], key=float)
    if set(thresholds) != set(solution["spell_f1"]):
        raise ValueError("Methods were evaluated at different IoU thresholds")
    headline = str(baseline["spell_iou_headline"])
    old, new = baseline["spell_f1"][headline], solution["spell_f1"][headline]
    prediction_source = ("Saved predictions from the recorded comparison; inference was not rerun."
                         if reused_predictions else "Predictions freshly generated by this comparison.")
    rows = [
        ("Official spellF1 (mean across IoU thresholds)", baseline["spell_f1_mean"], solution["spell_f1_mean"], ".4f"),
        (f"Possession F1 at IoU >= {headline}", old["f1"], new["f1"], ".4f"),
        ("Correctly matched possessions (TP)", old["n_matched"], new["n_matched"], "d"),
        ("Missed reference possessions (FN)", old["n_missed"], new["n_missed"], "d"),
        ("Unmatched predicted possessions (FP)", old["n_spurious"], new["n_spurious"], "d"),
        ("Precision: matched / predicted", old["precision"], new["precision"], ".2%"),
        ("Recall: matched / reference", old["recall"], new["recall"], ".2%"),
        ("Total predicted possessions", baseline["n_pred_spells"], solution["n_pred_spells"], "d"),
        ("Mean predicted possession duration (s)", baseline["mean_spell_duration_s"], solution["mean_spell_duration_s"], ".2f"),
    ]
    lines = [
        "# Possession detection quality: old versus new", "",
        f"Old: `{BASELINE}`. New: `{SOLUTION}`. Both use the same match and tactical tracking;",
        "the new method also uses supplied automatic Smart Tagging.", "",
        prediction_source, "",
        f"The unchanged official scorer evaluates {baseline['n_graded']:,} public frames",
        f"with **{baseline['n_gt_spells']} reference possessions**. Private full-match quality is unknown.", "",
        "## Possession detection", "",
        f"Counts, precision and recall below use IoU >= {headline}, with the correct team",
        "and one-to-one matching. IoU is temporal intersection divided by temporal union.",
        "Possessions are continuous H or A runs; dead-ball periods are not possessions.",
        "Official spellF1 is the mean F1 over IoU " + ", ".join(thresholds) + ".", "",
        "| Metric | Original baseline | New solution |",
        "|---|---:|---:|",
    ]
    for label, before, after, spec in rows:
        lines.append(f"| {label} | {before:{spec}} | {after:{spec}} |")
    lines.extend([
        "", f"Reference mean possession duration: {baseline['gt_mean_spell_duration_s']:.2f} s.",
        "Predicted counts or durations alone do not measure correct detection.", "",
        "## Sensitivity to temporal overlap", "",
        "A higher IoU threshold requires closer agreement on the start and end of a phase.", "",
        "| IoU | Old TP / FP / FN | New TP / FP / FN | Old precision | New precision | Old recall | New recall | Old F1 | New F1 |",
        "|---|---|---|---:|---:|---:|---:|---:|---:|",
    ])
    for threshold in thresholds:
        a, b = baseline["spell_f1"][threshold], solution["spell_f1"][threshold]
        lines.append(f"| {threshold} | {a['n_matched']} / {a['n_spurious']} / {a['n_missed']} | "
                     f"{b['n_matched']} / {b['n_spurious']} / {b['n_missed']} | "
                     f"{a['precision']:.2%} | {b['precision']:.2%} | {a['recall']:.2%} | {b['recall']:.2%} | "
                     f"{a['f1']:.4f} | {b['f1']:.4f} |")
    lines.extend([
        "", "## Interpretation and uncertainty", "",
        "Precision measures how many predicted phases match a reference phase. Recall measures",
        "how many reference phases are recovered. F1 balances both; it is not frame accuracy.",
        "An unmatched prediction may have the wrong team or insufficient temporal overlap;",
        "it does not necessarily represent an invented event.", "",
    ])
    if old["n_matched"] == new["n_matched"] and new["n_spurious"] < old["n_spurious"]:
        lines.extend([
            f"At IoU >= {headline}, both recover {new['n_matched']} of {baseline['n_gt_spells']} phases.",
            f"The new method reduces unmatched predictions from {old['n_spurious']} to {new['n_spurious']}.",
            "Its improvement at this threshold comes from precision, not additional recovered phases.", "",
        ])
    lines.extend(["| Official spellF1 bootstrap interval | 5th-95th percentile |", "|---|---:|"])
    for name, result in metrics.items():
        low, high = result["spell_bootstrap_low"], result["spell_bootstrap_high"]
        interval = "not computed" if low is None else f"{low:.4f} to {high:.4f}"
        lines.append(f"| {name} | {interval} |")
    lines.extend([
        "", f"Bootstrap draws: {baseline['bootstrap_n']:,}. Separate intervals are not a paired significance test.",
        "This small public window cannot establish superiority on the private full match.",
        "No model parameters, labels or method choices are changed by this diagnostic.",
        "The official reports are in `evaluation/reports/`. Prediction checksums and the exact",
        "aggregate metrics used here are recorded in `possession_quality.json`.", "",
    ])
    (output / "possession_quality.md").write_text("\n".join(lines), encoding="utf-8")
    report = {"methods": {"baseline": BASELINE, "solution": SOLUTION},
              "ground_truth": baseline["ground_truth"], "quality_frames": baseline["n_graded"],
              "reference_possessions": baseline["n_gt_spells"], "headline_iou": float(headline),
              "training_or_tuning": False, "prediction_source": prediction_source,
              "prediction_sha256": hashes, "official_metrics": metrics}
    (output / "possession_quality.json").write_text(
        json.dumps(report, indent=2, sort_keys=True, allow_nan=False) + "\n", encoding="utf-8")
    print(f"\nPossession detection quality: {baseline['n_graded']:,} public frames, "
          f"{baseline['n_gt_spells']} reference phases; counts at IoU >= {headline}.", flush=True)
    print(f"{'Metric':52} {'Old':>10} {'New':>10}", flush=True)
    for label, before, after, spec in rows:
        print(f"{label:52} {format(before, spec):>10} {format(after, spec):>10}", flush=True)
    print("\nHigher F1/precision/recall is better; lower FP/FN is better.", flush=True)
    print("These public results do not establish private full-match quality.", flush=True)
    print(f"Quality report: {output / 'possession_quality.md'}", flush=True)


def write_summary(output, timings, baseline, solution, inputs, bootstrap):
    """Present official aggregate metrics alongside independently measured runtime."""
    baseline_time = timings["results"][BASELINE]["median_s"]
    solution_time = timings["results"]["possession"]["median_s"]
    comparisons = [
        ("Full-match median runtime (s; lower is better)", baseline_time, solution_time),
        ("Public spellF1 (higher is better)", baseline["spell_f1_mean"], solution["spell_f1_mean"]),
        ("Public macroF1 (higher is better)", baseline["macro_f1"], solution["macro_f1"]),
        ("Public frame accuracy", baseline["accuracy"], solution["accuracy"]),
        ("Public dead-ball F1", baseline["per_class"]["D"]["f1"], solution["per_class"]["D"]["f1"]),
        ("Public dead-ball recall", baseline["per_class"]["D"]["recall"], solution["per_class"]["D"]["recall"]),
        ("Public predicted possessions", baseline["n_pred_spells"], solution["n_pred_spells"]),
        ("Public mean possession duration (s)", baseline["mean_spell_duration_s"], solution["mean_spell_duration_s"]),
    ]
    report = {
        "methods": {"baseline": BASELINE, "solution": SOLUTION},
        "scope": {"runtime_frames": GAMES[GAME]["n_video_frames"],
                  "quality_frames": baseline["n_graded"],
                  "quality_gt_possessions": baseline["n_gt_spells"],
                  "quality_gt_mean_possession_duration_s": baseline["gt_mean_spell_duration_s"],
                  "ground_truth": "public", "bootstrap_draws": bootstrap,
                  "training_or_tuning": False},
        "inputs_sha256": inputs,
        "timings": timings,
        "official_metrics": {BASELINE: baseline, SOLUTION: solution},
        "new_minus_old": {label: new - old for label, old, new in comparisons},
        "solution_time_divided_by_baseline": solution_time / baseline_time,
    }
    (output / "comparison.json").write_text(
        json.dumps(report, indent=2, sort_keys=True, allow_nan=False) + "\n", encoding="utf-8")
    lines = [
        "# Old-versus-new algorithm comparison", "",
        f"Old: `{BASELINE}`. New: `{SOLUTION}`. Both process the same match and tactical tracking.",
        "The new method additionally uses the supplied automatic Smart Tagging.", "",
        f"Runtime covers all {report['scope']['runtime_frames']:,} frames. Quality is evaluated only on",
        f"the {baseline['n_graded']:,} public frames ({baseline['n_gt_spells']} reference possessions).",
        "Full CLI timing includes startup, reading and writing. The new method also validates its",
        "output and creates a manifest. This is not an isolated algorithm-core benchmark.", "",
        "| Metric | Original baseline | New solution | New minus old |",
        "|---|---:|---:|---:|",
    ]
    lines.extend(f"| {label} | {old:.4f} | {new:.4f} | {new - old:+.4f} |"
                 for label, old, new in comparisons)
    lines.extend([
        "", f"The solution takes **{solution_time / baseline_time:.2f} times** the baseline's median runtime.",
        f"Reference mean possession duration: {baseline['gt_mean_spell_duration_s']:.2f} s.", "",
        f"## Official bootstrap intervals ({bootstrap:,} draws)", "",
        "| Metric | Original baseline | New solution |",
        "|---|---:|---:|",
    ])
    for label, low, high in [("spellF1", "spell_bootstrap_low", "spell_bootstrap_high"),
                              ("macroF1", "bootstrap_low", "bootstrap_high")]:
        def interval(result):
            return "not computed" if result[low] is None else f"{result[low]:.4f}–{result[high]:.4f}"
        lines.append(f"| {label}, 5th–95th percentile | {interval(baseline)} | {interval(solution)} |")
    lines.extend([
        "", "## Interpretation limits", "",
        "These are descriptive checks of two fixed methods, not training or parameter selection.",
        "The small public window cannot establish superiority on the private full match.",
        "Separate bootstrap intervals are not a paired significance test of the difference.",
        "A possession count closer to the reference is not itself proof of better segmentation.",
        "Raw match assets remain local. The default output location is under the ignored `artifacts/` directory;",
        "a custom `--output-dir` may need its own Git exclusion.",
        "The unchanged official scorer's full results are in `evaluation/scoreboard.csv` and `evaluation/reports/`.",
        "",
    ])
    text = "\n".join(lines)
    (output / "comparison.md").write_text(text, encoding="utf-8")
    print("\nHead-to-head summary (quality scores range from 0 to 1):", flush=True)
    print(f"{'Metric':52} {'Old':>10} {'New':>10} {'New-old':>10}", flush=True)
    for label, old, new in comparisons:
        print(f"{label:52} {old:10.4f} {new:10.4f} {new-old:+10.4f}", flush=True)
    print(f"\nReadable report: {output / 'comparison.md'}", flush=True)
    print(f"Machine-readable results: {output / 'comparison.json'}", flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runs", type=int, default=3, help="Measured runtime runs per method")
    parser.add_argument("--warmup", type=int, default=1, help="Unmeasured warm-up runs per method")
    parser.add_argument("--bootstrap", type=int, default=1000, help="Official bootstrap draws; 0 disables intervals")
    parser.add_argument("--quality-only", action="store_true",
                        help="Re-score existing, checksum-verified head-to-head CSVs; skip inference and runtime runs")
    parser.add_argument("--data-dir", type=Path, help="Alternative data bundle root for both methods")
    parser.add_argument("--output-dir", type=Path, default=ROOT / "artifacts" / "head-to-head")
    args = parser.parse_args()
    if args.runs < 1 or args.warmup < 0 or args.bootstrap < 0:
        parser.error("--runs must be positive; --warmup and --bootstrap must be non-negative")
    output = args.output_dir.resolve()
    results = output / "results"
    expected = {f"{BASELINE}.csv", f"{SOLUTION}.csv"}
    if any(path.name not in expected for path in results.glob("*.csv")):
        parser.error("Results directory contains unexpected CSV files; choose another --output-dir")
    environment = os.environ.copy()
    environment["PYTHONIOENCODING"] = "utf-8"
    if args.quality_only:
        if args.data_dir:
            parser.error("--data-dir cannot be combined with --quality-only, which uses saved predictions")
        try:
            timings = json.loads((output / "runtime" / "timings.json").read_text(encoding="utf-8"))
            for name, timing_key in ((BASELINE, BASELINE), (SOLUTION, "possession")):
                if sha256(results / f"{name}.csv") != timings["results"][timing_key]["csv_sha256"]:
                    parser.error(f"{name}: saved predictions differ from the recorded run; rerun without --quality-only")
        except (OSError, ValueError, KeyError, TypeError) as exc:
            parser.error(f"Cannot verify saved predictions: {exc}. Run without --quality-only first")
        print("Re-scoring the saved predictions; inference and runtime are not rerun.", flush=True)
        metrics, hashes = score_predictions(output, args.bootstrap, environment)
        write_quality_summary(output, metrics, hashes, reused_predictions=True)
        return
    results.mkdir(parents=True, exist_ok=True)
    paths = require(["atd_meta", "atd_raw", "smart_tagging"],
                    data_dir=str(args.data_dir.resolve()) if args.data_dir else None)
    inputs = {Path(path).name: sha256(path) for path in paths}
    benchmark = [sys.executable, str(ROOT / "benchmark_runtime.py"), "--runs", str(args.runs),
                 "--warmup", str(args.warmup), "--output-dir", str(output / "runtime")]
    if args.data_dir:
        benchmark.extend(["--data-dir", str(args.data_dir.resolve())])
    print("Step 1/2: regenerate both predictions and measure full-match runtime.", flush=True)
    subprocess.run(benchmark, cwd=ROOT, env=environment, check=True)
    if inputs != {Path(path).name: sha256(path) for path in paths}:
        raise RuntimeError("Input files changed during the comparison")
    shutil.copyfile(output / "runtime" / "baseline" / f"{BASELINE}.csv", results / f"{BASELINE}.csv")
    shutil.copyfile(output / "runtime" / "solution" / f"{SOLUTION}.csv", results / f"{SOLUTION}.csv")
    print("\nStep 2/2: score the two fixed outputs with the unchanged official public scorer.", flush=True)
    metrics, hashes = score_predictions(output, args.bootstrap, environment)
    timings = json.loads((output / "runtime" / "timings.json").read_text(encoding="utf-8"))
    write_summary(output, timings, metrics[BASELINE], metrics[SOLUTION], inputs, args.bootstrap)
    write_quality_summary(output, metrics, hashes)


if __name__ == "__main__":
    main()
